"""Evaluates the trained triage model against the holdout set, separately
from train.py's same-distribution validation split. Reports honestly: this
holdout (services/ml/data/holdout/triage.jsonl) is LLM-generated by
generate_holdout.py using a different prompt/seed/temperature than the
training data generator, as an explicit time-boxed demo compromise -- it is
NOT the independently human-written holdout technical.md §9.3 requires, and
every number below must be read with that caveat, not treated as a true
safety validation."""

import json

import torch
from torch.utils.data import DataLoader

from train import ACUITIES, FACILITIES, TriageDataset, TriageModel, build_input_text, evaluate, load_samples, MODEL_NAME

FULL_PATH = "services/ml/artifacts/triage/muril_v0_full.pt"
HEADS_PATH = "services/ml/artifacts/triage/muril_v0_heads.pt"
HOLDOUT_PATH = "services/ml/data/holdout/triage.jsonl"


def main() -> None:
    device = "cuda" if torch.cuda.is_available() else "cpu"
    samples = load_samples(HOLDOUT_PATH)
    print(f"loaded {len(samples)} holdout samples")

    from transformers import AutoTokenizer
    tokenizer = AutoTokenizer.from_pretrained(MODEL_NAME)

    texts = [build_input_text(s) for s in samples]
    acuity_labels = [ACUITIES.index(s["acuity"]) for s in samples]
    facility_labels = [FACILITIES.index(s["facility"]) for s in samples]

    ds = TriageDataset(texts, acuity_labels, facility_labels, tokenizer)
    loader = DataLoader(ds, batch_size=16)

    model = TriageModel(MODEL_NAME).to(device)
    import os
    if os.path.exists(FULL_PATH):
        # Encoder was fine-tuned -- load the full state, not just the heads.
        state = torch.load(FULL_PATH, map_location=device)
        model.load_state_dict(state, strict=True)
    else:
        state = torch.load(HEADS_PATH, map_location=device)
        model.load_state_dict(state, strict=False)

    metrics = evaluate(model, loader, device)

    report = {
        **metrics,
        "n_holdout": len(samples),
        "caveat": "This holdout is LLM-generated (generate_holdout.py), NOT the independently "
                  "human-written holdout technical.md Section 9.3 requires. These numbers are a "
                  "stress-test against a distinct prompt/seed/temperature, not a verified "
                  "real-world safety guarantee. Replace with a real human-written holdout before "
                  "treating critical_recall here as a safety claim.",
    }
    with open("services/ml/training/triage/HOLDOUT_REPORT.json", "w") as f:
        json.dump(report, f, indent=2)
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
